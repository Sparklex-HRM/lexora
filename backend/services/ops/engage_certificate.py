"""Course certificate → PDF (fpdf2 + the bundled Unicode font, shared/utils/pdf_fonts.py). Pure: no DB."""
from __future__ import annotations

from shared.utils.pdf_fonts import UnicodePDF, pdf_text  # noqa: F401  (pdf_text re-exported)


def render_certificate(*, person: str, course: str, number: str, completed_on: str, org_name: str, score: int | None) -> bytes:
    """A plain A4-landscape certificate."""
    pdf = UnicodePDF(orientation="L", format="A4")
    pdf.set_auto_page_break(False)
    pdf.add_page()
    pdf.set_draw_color(101, 34, 214)
    pdf.set_line_width(1.2)
    pdf.rect(10, 10, 277, 190)
    pdf.set_line_width(0.3)
    pdf.rect(14, 14, 269, 182)
    pdf.set_text_color(83, 24, 180)
    pdf.set_font("Helvetica", "B", 30)
    pdf.set_y(40)
    pdf.cell(0, 14, "Certificate of Completion", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(23, 35, 43)
    pdf.set_font("Helvetica", "", 13)
    pdf.set_y(70)
    pdf.cell(0, 8, "This certifies that", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "B", 24)
    pdf.set_y(84)
    pdf.cell(0, 12, pdf_text(person), align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 13)
    pdf.set_y(104)
    pdf.cell(0, 8, "has completed the course", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_y(116)
    pdf.multi_cell(0, 9, pdf_text(course), align="C")
    pdf.set_font("Helvetica", "", 12)
    pdf.set_y(140)
    line = f"Completed on {completed_on}" + (f"  |  Quiz score {score}%" if score is not None else "")
    pdf.cell(0, 8, pdf_text(line), align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_y(160)
    pdf.set_font("Helvetica", "", 11)
    pdf.cell(0, 7, pdf_text(org_name), align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(90, 107, 115)
    pdf.set_font("Helvetica", "", 9)
    pdf.set_y(182)
    pdf.cell(0, 6, pdf_text(f"Certificate no. {number}  |  Generated by Lexora HRM"), align="C")
    return bytes(pdf.output())
