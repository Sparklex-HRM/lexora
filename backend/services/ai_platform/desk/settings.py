"""HR Desk org settings — ONE place for every configurable default (company setting group ``ai_desk``,
written through the ordinary ``PUT /settings/ai_desk`` as org_admin, read here with ``get_setting``).

Nothing statutory is hard-coded as a product truth: the designated recipient for sexual-harassment complaints is
whoever the org's workplace harassment policy names (Ontario OHSA Part III.0.1 / the federal Work Place Harassment and
Violence Prevention Regulations / the province's own rules); the helpline is Canada's 9-8-8 suicide crisis line and is
replaceable per org.
"""
from __future__ import annotations

import copy
import sys

sys.path.append("/app")
from shared.utils.org_settings import get_setting  # noqa: E402

GROUP = "ai_desk"

# Who receives sealed sexual-harassment referrals (internal ids keep the ``ic`` name): a per-org list of login ids — the
# designated recipient(s) the workplace harassment policy names — AND/OR a custom role whose key is ``ic_member``
# (Roles & Permissions, built on Employee / own reach; the gateway stamps it as X-Acting-Role).
IC_ROLE_KEY = "ic_member"

DEFAULTS: dict = {
    # retrieval: normalised relevance 0..1 (desk.policy_store.relevance) under which the desk abstains
    "abstain_threshold": 0.35,
    "top_k": 5,
    "ic": {
        "presiding_officer_name": "",
        "presiding_officer_contact": "",       # e-mail / phone shown in the sexual-harassment template
        "members": [],                         # login ids (user_id) who may see desk_ic_referrals
        "external_member_contact": "",
    },
    # fixed, non-generative texts; {placeholders} are filled from the ic block above
    "templates": {},                           # {class_key: text} overrides of desk.router.DEFAULT_TEMPLATES
    # hours to first human response by hard-route / hand-off class (product policy, not statute)
    "sla_hours": {"sexual_harassment": 24, "harassment": 24, "medical": 48, "mental_health": 4, "grievance": 24,
                  "disciplinary": 48, "whistleblowing": 24, "legal": 24, "salary_dispute": 48,
                  "other_person_data": 72, "handoff": 48},
    "helpline": {"name": "Talk Suicide Canada — 9-8-8 (24/7, free, English and French)", "number": "9-8-8 (call or text)"},
    "disclosure": "This answer was generated by AI from your company's approved policies and your own records. "
                  "It is not legal or medical advice. You can ask a person at any time.",
    "handoff_unresolved_attempts": 2,
    "handoff_abstains": 2,
}


def defaults() -> dict:
    return copy.deepcopy(DEFAULTS)


def _merge(base: dict, over: dict | None) -> dict:
    out = copy.deepcopy(base)
    for k, v in (over or {}).items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = _merge(out[k], v)
        elif v is not None:
            out[k] = v
    return out


async def load(org_id: str) -> dict:
    """Stored ai_desk settings laid over the defaults. Never raises."""
    try:
        stored = await get_setting(org_id, GROUP, {}) or {}
    except Exception:                                        # noqa: BLE001
        stored = {}
    return _merge(DEFAULTS, stored if isinstance(stored, dict) else {})


def is_ic_member(cfg: dict, user_id: str | None, acting_role: str | None) -> bool:
    """IC access = listed login OR the ``ic_member`` custom role. Roles alone (org_admin, HR) never qualify."""
    members = {str(m) for m in ((cfg.get("ic") or {}).get("members") or [])}
    if user_id and str(user_id) in members:
        return True
    return (acting_role or "").strip().lower() == IC_ROLE_KEY
